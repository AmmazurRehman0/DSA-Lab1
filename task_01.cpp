#include <iostream>
using namespace std;
int main(){
    cout<<"Memory occupied by int : "<<sizeof(int)<<"bytes\n";
    cout<<"Memory occupied by long : "<<sizeof(long)<<"bytes\n";
    cout<<"Memory occupied by double : "<<sizeof(double)<<"bytes\n";
    cout<<"Memory occupied by float : "<<sizeof(float)<<"bytes\n";
    cout<<"Memory occupied by char : "<<sizeof(char)<<"bytes\n";
    return 0;
}
